COPILOT = f'''{MARKER}
# Shared AI Engineering Guidance

Follow `AGENTS.md` and the canonical standards in `.agent-engineering/core/`. Before non-trivial changes, inspect relevant implementation, tests, data models, integrations, and conventions. Design for the complete workflow and appropriate failure states. Run relevant checks and report what was verified. Propose evidence-based improvements; do not silently rewrite permanent standards.
'''


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def safe_relative_path(relative: str) -> Path:
    path = Path(relative)
    if path.is_absolute() or any(part == ".." for part in path.parts):
        raise ValueError(f"Invalid managed path: {relative}")
    return path


def safe_destination(project: Path, relative: str) -> Path:
    path = safe_relative_path(relative)
    destination = project / path
    project_root = project.resolve()
    resolved = destination.resolve(strict=False)
    try:
        resolved.relative_to(project_root)
    except ValueError as exc:
        raise ValueError(f"Managed path escapes project: {relative}") from exc
    current = project_root
    for part in path.parts:
        current /= part
        if current.exists() and current.is_symlink():
            raise ValueError(f"Managed path uses a symbolic link: {relative}")
    return destination


def validate_destinations(project: Path, relative_paths: list[str]) -> None:
    for relative in relative_paths:
        safe_destination(project, relative)


def wrapper(source: Path) -> str:
    raw = source.read_text(encoding="utf-8")
    parts = raw.split("---", 2)
    if len(parts) < 3:
        raise ValueError(f"Invalid skill frontmatter: {source}")
    front = parts[1]
    name = re.search(r"(?m)^name:\s*(.+)$", front)
    desc = re.search(r"(?m)^description:\s*(.+)$", front)
    if not name or not desc:
        raise ValueError(f"Missing name or description: {source}")
    canonical = f".agent-engineering/skills/{source.parent.name}/SKILL.md"
    return f"---\nname: {name.group(1).strip()}\ndescription: {desc.group(1).strip()}\n---\n\nGenerated adapter: read and follow `{canonical}`. The canonical copy is the source of truth.\n"


def outputs(selected: set[str]) -> dict[str, str]:
    result = {"AGENTS.md": AGENTS}
    if "claude" in selected:
        result["CLAUDE.md"] = CLAUDE
    if "antigravity" in selected:
        result[".agents/rules/aes.md"] = GEMINI
    if "copilot" in selected:
        result[".github/copilot-instructions.md"] = COPILOT
    return result


def targets(selected: set[str]) -> list[str]:
    result = []
    if "codex" in selected or "antigravity" in selected:
        result.append(".agents/skills")
    if "claude" in selected:
        result.append(".claude/skills")
    if "copilot" in selected:
        result.append(".github/skills")
    return result


def source_files() -> list[Path]:
    return [
        path
        for root in (ROOT / "core", ROOT / "skills")
        for path in root.rglob("*")
        if path.is_file()
    ]


def managed_content(selected: set[str]) -> dict[str, bytes]:
    sources = sorted((ROOT / "skills").glob("*/SKILL.md"))
    content = {
        (Path(".agent-engineering") / path.relative_to(ROOT)).as_posix(): path.read_bytes()
        for path in source_files()
    }
    content[".agent-engineering/VERSION"] = (ROOT / "VERSION").read_bytes()
    content[".agent-engineering/improvement-backlog.md"] = (
        b"# Improvement Backlog\n\nRecord evidence-based proposals here. Do not silently modify permanent standards.\n"
    )
    content.update({rel: value.encode("utf-8") for rel, value in outputs(selected).items()})
    for target in targets(selected):
        for source in sources:
            content[(Path(target) / source.parent.name / "SKILL.md").as_posix()] = (
                wrapper(source).encode("utf-8")
            )
    return content


def write_manifest(project: Path, files: list[str]) -> None:
    manifest_path = safe_destination(project, ".agent-engineering/" + MANIFEST)
    records = {
        rel: digest(safe_destination(project, rel))
        for rel in sorted(files)
        if safe_destination(project, rel).is_file()
    }
    data = {
        "version": (ROOT / "VERSION").read_text(encoding="utf-8").strip(),
        "files": records,
    }
    manifest_path.write_text(
        json.dumps(data, indent=2) + "\n", encoding="utf-8"
    )


def read_manifest(project: Path) -> dict:
    path = safe_destination(project, ".agent-engineering/" + MANIFEST)
    if not path.is_file():
        raise ValueError(f"Missing {path}; reinstall AES before using --update.")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid AES manifest: {path}") from exc
    if not isinstance(data.get("files"), dict):
        raise ValueError(f"Invalid AES manifest files entry: {path}")
    for relative in data["files"]:
        if not isinstance(relative, str):
            raise ValueError("Invalid AES manifest path entry")
        safe_destination(project, relative)
    return data


def stage_files(project: Path, content: dict[str, bytes]) -> Path:
    staging = Path(tempfile.mkdtemp(prefix=".aes-stage-", dir=project))
    try:
        for relative, data in content.items():
            destination = safe_destination(project, relative)
            staged = staging / safe_relative_path(relative)
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_bytes(data)
            if digest(staged) != hashlib.sha256(data).hexdigest():
                raise OSError(f"Staging verification failed: {relative}")
        return staging
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise


def apply_transaction(project: Path, content: dict[str, bytes], manifest_files: list[str]) -> None:
    validate_destinations(project, list(content))
    staging = stage_files(project, content)
    backup = Path(tempfile.mkdtemp(prefix=".aes-backup-", dir=project))
    applied: list[tuple[Path, Path | None]] = []
    created_dirs: list[Path] = []
    manifest_path = safe_destination(project, ".agent-engineering/" + MANIFEST)
    try:
        manifest_data = {
            "version": (ROOT / "VERSION").read_text(encoding="utf-8").strip(),
            "files": {
                relative: hashlib.sha256(content[relative]).hexdigest()
                if relative in content
                else digest(safe_destination(project, relative))
                for relative in sorted(manifest_files)
                if relative in content or safe_destination(project, relative).is_file()
            },
        }
        manifest_stage = staging / ".agent-engineering" / MANIFEST
        manifest_stage.parent.mkdir(parents=True, exist_ok=True)
        manifest_stage.write_text(json.dumps(manifest_data, indent=2) + "\n", encoding="utf-8")
        all_paths = [*content, ".agent-engineering/" + MANIFEST]
        for relative in all_paths:
            destination = safe_destination(project, relative)
            backup_path = None
            if destination.exists():
                backup_path = backup / safe_relative_path(relative)
                backup_path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(destination, backup_path)
            applied.append((destination, backup_path))
            source = staging / safe_relative_path(relative)
            missing_parents = []
            parent = destination.parent
            while not parent.exists():
                missing_parents.append(parent)
                parent = parent.parent
            destination.parent.mkdir(parents=True, exist_ok=True)
            created_dirs.extend(missing_parents)
            os.replace(source, destination)
    except Exception:
        for destination, backup_path in reversed(applied):
            if backup_path is not None and backup_path.exists():
                os.replace(backup_path, destination)
            elif destination.exists():
                destination.unlink()
        for directory in sorted(created_dirs, key=lambda path: len(path.parts), reverse=True):
            try:
                directory.rmdir()
            except OSError:
                pass
        raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        shutil.rmtree(backup, ignore_errors=True)


def install(project: Path, selected: set[str], update: bool) -> int:
    proposed = managed_content(selected)
    aes = project / ".agent-engineering"
    if update:
        try:
            previous = read_manifest(project)["files"]
        except ValueError as exc:
            print(str(exc), file=sys.stderr)
            return 3
        conflicts = []
        for rel, expected in previous.items():
            path = safe_destination(project, rel)
            if not path.exists():
                conflicts.append(f"{rel} (removed locally)")
            elif digest(path) != expected:
                conflicts.append(rel)
        for rel, content in proposed.items():
            path = safe_destination(project, rel)
            if path.exists() and rel not in previous and path.read_bytes() != content:
                conflicts.append(rel)
        if conflicts:
            print("Refusing to overwrite locally modified AES files:", file=sys.stderr)
            print("\n".join(f" - {rel}" for rel in conflicts), file=sys.stderr)
            print("Review or remove the local changes, then rerun --update.", file=sys.stderr)
            return 3
        existing = [
            rel for rel in previous
            if safe_destination(project, rel).is_file()
        ]
        try:
            apply_transaction(project, proposed, list(set(proposed) | set(existing)))
        except (OSError, ValueError, shutil.Error) as exc:
            print(f"AES update failed; no changes were committed: {exc}", file=sys.stderr)
            return 3
        print("AES updated. Local modifications were preserved.")
        return 0

    if aes.exists():
        print("Refusing to overwrite existing .agent-engineering/; use --update for a managed installation.", file=sys.stderr)
        return 3
    conflicts = [rel for rel in outputs(selected) if (project / rel).exists()]
    conflicts += [
        str(Path(target) / source.parent.name / "SKILL.md")
        for target in targets(selected)
        for source in sorted((ROOT / "skills").glob("*/SKILL.md"))
        if (project / target / source.parent.name / "SKILL.md").exists()
    ]
    if conflicts:
        print("Refusing to overwrite existing instruction or skill files:", file=sys.stderr)
        print("\n".join(f" - {rel}" for rel in conflicts), file=sys.stderr)
        print("No files were changed.", file=sys.stderr)
        return 3
    try:
        apply_transaction(project, proposed, list(proposed))
    except (OSError, ValueError, shutil.Error) as exc:
        print(f"AES installation failed; no changes were committed: {exc}", file=sys.stderr)
        return 3
    print("AES installed. Review the diff and open a fresh agent session.")
    print("Canonical standards: .agent-engineering/core/")
    print("Generated entry points:\n" + "\n".join(f" - {p}" for p in outputs(selected)))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Install or safely update AES without overwriting local instructions."
    )
    parser.add_argument("project", type=Path)
    parser.add_argument("--agents", default="codex,claude,antigravity,copilot")
    parser.add_argument(
        "--update",
        action="store_true",
        help="Update a prior AES installation; refuse locally modified managed files.",
    )
    args = parser.parse_args()
    project = args.project.resolve()
    if not project.is_dir():
        print(f"Target directory does not exist: {project}", file=sys.stderr)
        return 2
    valid = {"codex", "claude", "antigravity", "copilot"}
    selected = {item.strip().lower() for item in args.agents.split(",") if item.strip()}
    if not selected or selected - valid:
        print(f"Choose one or more of: {', '.join(sorted(valid))}", file=sys.stderr)
        return 2
    return install(project, selected, args.update)


if __name__ == "__main__":
    raise SystemExit(main())
